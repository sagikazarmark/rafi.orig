//! The two schemas, `migrations/sqlite` and `migrations/postgres`, are kept by
//! hand. They must declare the same tables, columns, constraints and indexes,
//! differing only where the dialects do: integer types (`BIGINT`), the
//! identity column, and the triggers (which each dialect writes its own way,
//! and the conformance suite checks by behaviour). A column added to one
//! migration and not the other fails here, before a backend does.

use std::collections::BTreeMap;

const SQLITE: &str = include_str!("../../../migrations/sqlite/0001_init.sql");
const POSTGRES: &str = include_str!("../../../migrations/postgres/0001_init.sql");

/// The schema's tables and indexes, by name: each statement without
/// comments, whitespace collapsed, the dialects' differences mapped to one
/// spelling. Triggers and their functions are left out.
fn shape(sql: &str) -> BTreeMap<String, String> {
    let without_comments: String = sql
        .lines()
        .map(|l| l.split("--").next().unwrap_or(""))
        .collect::<Vec<_>>()
        .join(" ");
    let mut shape = BTreeMap::new();
    let mut rest = without_comments.as_str();
    while let Some(start) = rest.find("CREATE ") {
        rest = &rest[start..];
        // A function body may hold semicolons: skip it whole.
        let end = if rest.starts_with("CREATE FUNCTION") {
            let body = rest.find("$$").expect("a function body");
            body + 2 + rest[body + 2..].find("$$;").expect("its end") + 3
        } else if rest.starts_with("CREATE TRIGGER")
            && rest.contains("BEGIN")
            && rest.find("BEGIN") < rest.find(';')
        {
            rest.find("END;").expect("a trigger's end") + 4
        } else {
            rest.find(';').expect("a statement's end") + 1
        };
        let statement = rest[..end].split_whitespace().collect::<Vec<_>>().join(" ");
        rest = &rest[end..];
        if statement.starts_with("CREATE TRIGGER") || statement.starts_with("CREATE FUNCTION") {
            continue;
        }
        let normal = statement
            .replace(
                "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                "INTEGER PRIMARY KEY AUTOINCREMENT",
            )
            .replace("BIGINT", "INTEGER")
            .replace("( ", "(")
            .replace(" )", ")");
        let name = normal
            .split_whitespace()
            .skip_while(|w| !matches!(*w, "TABLE" | "INDEX"))
            .nth(1)
            .expect("a name")
            .to_owned();
        assert!(shape.insert(name.clone(), normal).is_none(), "{name} twice");
    }
    shape
}

#[test]
fn the_sqlite_and_postgres_schemas_agree() {
    let (sqlite, postgres) = (shape(SQLITE), shape(POSTGRES));
    assert!(sqlite.len() > 10, "{:?}", sqlite.keys());
    let names: Vec<_> = sqlite.keys().chain(postgres.keys()).collect();
    for name in names {
        assert_eq!(
            sqlite.get(name),
            postgres.get(name),
            "{name}: sqlite (left) and postgres (right) differ"
        );
    }
}

/// The triggers keep the raffle's version and its log's integrity on both:
/// each dialect has one for the same tables.
#[test]
fn both_schemas_have_triggers_on_the_same_tables() {
    let tables = |sql: &str| {
        let mut on: Vec<String> = sql
            .split("CREATE TRIGGER")
            .skip(1)
            .filter_map(|t| {
                let words: Vec<&str> = t.split_whitespace().collect();
                let i = words.iter().position(|w| *w == "ON")?;
                Some(words[i + 1].to_owned())
            })
            .collect();
        on.sort();
        on.dedup();
        on
    };
    assert_eq!(tables(SQLITE), tables(POSTGRES));
}
