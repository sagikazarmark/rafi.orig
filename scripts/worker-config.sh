#!/usr/bin/env bash
# Writes one installation's copy of the Worker's configuration:
# apps/worker/wrangler.<site>.toml is apps/worker/wrangler.toml with the
# installation's D1 database ID in place of the placeholder, for
# `wrangler deploy -c wrangler.<site>.toml`. The copy is untracked and never
# edited by hand: run this again after every upgrade, so the shape is always
# the release's and the ID is always yours. Everything else of the
# installation's is a secret (see wrangler.toml).
#
#   ./scripts/worker-config.sh <site> <d1 database id>
#   ./scripts/worker-config.sh prod 1b2c3d4e-...        # -> apps/worker/wrangler.prod.toml
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SITE="${1:?usage: worker-config.sh <site> <d1 database id>}"
DB_ID="${2:?usage: worker-config.sh <site> <d1 database id>}"
case "$SITE" in
  *[!A-Za-z0-9_-]*|"") echo "site must be letters, digits, - or _" >&2; exit 1 ;;
esac
case "$DB_ID" in
  [0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]-*) ;;
  *) echo "that doesn't look like a D1 database ID (wrangler d1 create rafi --jurisdiction eu)" >&2; exit 1 ;;
esac

SRC="$ROOT/apps/worker/wrangler.toml"
OUT="$ROOT/apps/worker/wrangler.$SITE.toml"
PLACEHOLDER="00000000-0000-0000-0000-000000000000"
{
  echo "# Generated by scripts/worker-config.sh from wrangler.toml: do not edit, run it again after an upgrade."
  echo "# site: $SITE"
  # The placeholder appears in the production binding and in [env.dev]'s;
  # the copy is for production, so both get the ID (dev isn't run from it).
  sed "s/$PLACEHOLDER/$DB_ID/g" "$SRC"
} >"$OUT"
echo "wrote $OUT"
echo "deploy with: (cd apps/worker && wrangler deploy -c wrangler.$SITE.toml)"
